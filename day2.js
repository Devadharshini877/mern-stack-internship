// Simple Calculator

let a = 20;
let b = 10;
let operation = "+";

if (operation === "+") {
    console.log("Result:", a + b);
} else if (operation === "-") {
    console.log("Result:", a - b);
} else if (operation === "*") {
    console.log("Result:", a * b);
} else if (operation === "/") {
    console.log("Result:", a / b);
} else {
    console.log("Invalid Operation");
}